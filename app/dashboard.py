def tab_overview(data, dark):
    cur = data["current"]
    fc = data["forecast"]

    worst = fc.loc[fc["aqi"].idxmax()]
    if worst["aqi"] >= 150:
        st.markdown(
            f'<div class="alert"><b>Air quality alert</b> &nbsp;AQI reaches '
            f'{int(worst["aqi"])} ({worst["category"]}) at '
            f'{pd.Timestamp(worst["timestamp"]).strftime("%A %H:%M")}. '
            f'Sensitive groups should limit outdoor activity.</div>',
            unsafe_allow_html=True)

    trend = cur.get("trend_24h", cur.get("trend_6h", 0))
    arrow = "↓" if trend < 0 else "↑" if trend > 0 else "→"
    colour = CATEGORY_DOT.get(cur["category"], "#8e8e88")

    left, right = st.columns([1, 3])
    with left:
        st.markdown(
            f'<div class="card"><div class="lbl">RIGHT NOW</div>'
            f'<div style="display:flex;align-items:baseline;gap:10px;margin:10px 0">'
            f'<span class="hero-num">{cur["aqi"]}</span>'
            f'<span style="font-size:14px;color:var(--ac)">{arrow} '
            f'{abs(trend):.0f}</span></div>'
            f'<div><span class="pill"><span class="dot" '
            f'style="background:{colour}"></span>{cur["category"]}</span></div>'
            f'<div class="sub" style="margin-top:11px">driven by '
            f'{cur["dominant_pollutant"].replace("pm2_5","PM2.5").upper()}'
            f' &middot; vs 24 h ago</div></div>', unsafe_allow_html=True)

    with right:
        a, b, c = st.columns(3)
        a.markdown(card("TEMPERATURE", f'{cur["temperature"]:.0f}°', "Celsius"),
                   unsafe_allow_html=True)
        b.markdown(card("HUMIDITY", f'{cur["humidity"]}%',
                        "Dry" if cur["humidity"] < 50 else "Humid"),
                   unsafe_allow_html=True)
        c.markdown(card("WIND", f'{cur["wind_speed"]:.0f}', "km/h"),
                   unsafe_allow_html=True)

        st.markdown("<div style='height:8px'></div>", unsafe_allow_html=True)
        cols = st.columns(3)
        for col, (_, row) in zip(cols, data["daily"].iterrows()):
            dc = CATEGORY_DOT.get(row["category"], "#8e8e88")
            col.markdown(
                f'<div class="card"><div class="lbl">DAY +{row["day"]}</div>'
                f'<div class="val">{row["mean_aqi"]}</div>'
                f'<div class="sub"><span class="dot" style="background:{dc}">'
                f'</span>{row["min_aqi"]}&ndash;{row["max_aqi"]}</div></div>',
                unsafe_allow_html=True)

    st.markdown("<div style='height:18px'></div>", unsafe_allow_html=True)
    st.markdown("##### Next 72 hours")
    bounds = [fc[fc["day"] == d]["timestamp"].iloc[0] for d in (2, 3)
              if len(fc[fc["day"] == d])]
    st.plotly_chart(line_chart(fc["timestamp"], fc["aqi"], dark,
                               height=280, markers=False, dividers=bounds),
                    use_container_width=True, config={"displayModeBar": False})


def tab_forecast(data, dark):
    fc = data["forecast"]
    mode = st.radio("View", ["Whole day", "Specific hour"],
                    horizontal=True, label_visibility="collapsed")

    if mode == "Whole day":
        day = st.radio("Day", ["Day +1", "Day +2", "Day +3"],
                       horizontal=True, label_visibility="collapsed")
        d = int(day[-1])
        block = fc[fc["day"] == d]
        st.plotly_chart(line_chart(block["timestamp"], block["aqi"], dark),
                        use_container_width=True,
                        config={"displayModeBar": False})
    else:
        h = st.slider("Hours ahead", 1, 72, 18, label_visibility="collapsed")
        row = fc[fc["hours_ahead"] == h].iloc[0]
        colour = CATEGORY_DOT.get(row["category"], "#8e8e88")
        when = pd.Timestamp(row["timestamp"])
        c1, c2 = st.columns([1, 1])
        c1.markdown(
            f'<div class="card"><div class="lbl">'
            f'{when.strftime("%A %d %B &middot; %H:%M")} UTC</div>'
            f'<div class="hero-num" style="margin:12px 0">{int(row["aqi"])}</div>'
            f'<div><span class="pill"><span class="dot" '
            f'style="background:{colour}"></span>{row["category"]}</span></div>'
            f'<div class="sub" style="margin-top:10px">{h} hours ahead '
            f'&middot; day +{int(row["day"])} model</div></div>',
            unsafe_allow_html=True)
        with c2:
            st.plotly_chart(gauge(int(row["aqi"]), dark),
                            use_container_width=True,
                            config={"displayModeBar": False})

    # Measured, not forecast - the models predict AQI directly, not
    # individual pollutants, so this panel does not follow the day
    # selector and the heading has to say so.
    st.markdown("<div style='height:16px'></div>", unsafe_allow_html=True)
    st.markdown("##### Pollutants now")
    st.markdown(f'<div class="foot" style="margin:-8px 0 10px">measured at '
                f'{pd.Timestamp(data["predicted_from"]).strftime("%H:%M")} UTC '
                f'&middot; current readings, not a forecast</div>',
                unsafe_allow_html=True)

    pol = cur_pollutants(data)
    hist = data.get("pollutant_history", {})
    names = {"pm2_5": "PM2.5", "pm10": "PM10", "no2": "NO₂",
             "o3": "O₃", "co": "CO", "so2": "SO₂"}
    cols = st.columns(6)
    for col, (k, label) in zip(cols, names.items()):
        unit = "ppm" if k == "co" else "µg/m³"
        val = pol[k] / 1145 if k == "co" else pol[k]
        col.markdown(
            f'<div class="card" style="padding:13px">'
            f'<div class="lbl">{label}</div>'
            f'<div class="val" style="font-size:22px">{val:.1f}</div>'
            f'<div class="sub">{unit}</div>{spark(hist.get(k))}</div>',
            unsafe_allow_html=True)


def cur_pollutants(data):
    return data["current"]["pollutants"]


def spark(series):
    """A 48-hour sparkline, or nothing if there is no history."""
    if not series or len(series) < 5:
        return ""
    lo, hi = min(series), max(series)
    rng = max(hi - lo, 1e-6)
    pts = " ".join("%.1f,%.1f" % (i / (len(series) - 1) * 70,
                                  14 - (v - lo) / rng * 12)
                   for i, v in enumerate(series))
    return (f'<svg viewBox="0 0 70 14" style="width:100%;height:14px;'
            f'margin-top:7px;opacity:.65"><polyline points="{pts}" fill="none" '
            f'stroke="var(--ac)" stroke-width="1.2"/></svg>')


def tab_accuracy(data, dark):
    st.markdown("##### Model performance")
    st.markdown('<div class="foot" style="margin:-8px 0 12px">R&sup2; on a '
                'held-out test period, per forecast horizon</div>',
                unsafe_allow_html=True)

    cols = st.columns(3)
    for col, key in zip(cols, ["day1", "day2", "day3"]):
        m = data["models"].get(key, {})
        r2 = m.get("r2") or 0
        pct = int(round(r2 * 100))
        col.markdown(
            f'<div class="card"><div class="lbl">DAY +{key[-1]}</div>'
            f'<div class="val">{pct}<span style="font-size:15px">%</span></div>'
            f'<div class="bar-track"><div class="bar-fill" '
            f'style="width:{pct}%"></div></div>'
            f'<div class="foot">R&sup2; {r2:.3f}<br>'
            f'MAE {m.get("mae") or 0:.1f} &middot; RMSE {m.get("rmse") or 0:.1f}'
            f'<br>{m.get("source","")}</div></div>', unsafe_allow_html=True)

    st.markdown("<div style='height:18px'></div>", unsafe_allow_html=True)
    st.markdown(
        '<div class="foot">Accuracy falls with lead time, as forecasts '
        'naturally do. Each model is also compared against a persistence '
        'baseline - predicting that AQI stays exactly as it is now - which '
        'is a strong benchmark for air quality because it changes slowly. '
        'The models beat it by +0.022, +0.034 and +0.069 R&sup2; at day +1, '
        '+2 and +3, so their advantage grows as forecasting gets harder.'
        '</div>', unsafe_allow_html=True)


def tab_history(data, dark):
    span = st.radio("Range", ["24 hours", "7 days", "30 days"],
                    horizontal=True, label_visibility="collapsed", index=2)
    hours = {"24 hours": 24, "7 days": 24 * 7, "30 days": 24 * 30}[span]
    hist = data["history"].tail(hours)
    st.plotly_chart(
        line_chart(hist["timestamp"], hist["aqi"], dark, height=340,
                   markers=(hours <= 24)),
        use_container_width=True, config={"displayModeBar": False})

    c1, c2, c3, c4 = st.columns(4)
    c1.markdown(card("AVERAGE", "%d" % hist["aqi"].mean(), "over the period"),
                unsafe_allow_html=True)
    c2.markdown(card("HIGHEST", "%d" % hist["aqi"].max(), "peak reading"),
                unsafe_allow_html=True)
    c3.markdown(card("LOWEST", "%d" % hist["aqi"].min(), "cleanest hour"),
                unsafe_allow_html=True)
    c4.markdown(card("READINGS", "%d" % len(hist), "hourly observations"),
                unsafe_allow_html=True)


