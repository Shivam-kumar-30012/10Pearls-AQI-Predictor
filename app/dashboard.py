@st.cache_data(ttl=3600, show_spinner=False)
def read_shap():
    """
    The SHAP explanations, written by pipeline/11_explain.py.

    Committed as JSON plus PNGs rather than computed here: SHAP needs
    the model files and xgboost, neither of which the deployed app
    carries, and the explanations only change when the models do.
    """
    if not SHAP_SUMMARY.exists():
        return None
    with open(SHAP_SUMMARY) as f:
        return json.load(f)


@st.cache_data(ttl=3600, show_spinner=False)
def read_snapshot():
    if not SNAPSHOT.exists():
        return None
    with open(SNAPSHOT) as f:
        snap = json.load(f)

    fc = pd.DataFrame(snap["forecast"])
    fc["timestamp"] = pd.to_datetime(fc["timestamp"], utc=True)
    hi = pd.DataFrame(snap["history"])
    hi["timestamp"] = pd.to_datetime(hi["timestamp"], utc=True)

    return {
        "mode": "snapshot", "current": snap["current"], "forecast": fc,
        "daily": pd.DataFrame(snap["daily"]), "history": hi,
        "models": snap["models"],
        "predicted_from": pd.Timestamp(snap["predicted_from"]),
        "source": "snapshot &middot; " + snap["generated_at"][:16].replace("T", " "),
        "pollutant_history": snap.get("pollutant_history", {}),
    }


