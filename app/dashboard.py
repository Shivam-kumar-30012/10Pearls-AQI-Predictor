def line_chart(x, y, dark, height=260, fill=True):
    tx = "#f2f2f0" if dark else "#0b0b0b"
    grid = "rgba(255,255,255,.07)" if dark else "rgba(0,0,0,.07)"
    ft = "#5c5c57" if dark else "#9a9a94"

    fig = go.Figure()
    if fill:
        fig.add_trace(go.Scatter(
            x=x, y=y, mode="lines", line=dict(width=0),
            fill="tozeroy",
            fillcolor="rgba(255,255,255,.06)" if dark else "rgba(0,0,0,.04)",
            hoverinfo="skip", showlegend=False))
    fig.add_trace(go.Scatter(
        x=x, y=y, mode="lines+markers",
        line=dict(color=tx, width=2, shape="spline", smoothing=0.6),
        marker=dict(size=5, color=tx),
        hovertemplate="AQI %{y}<br>%{x|%a %H:%M}<extra></extra>",
        showlegend=False))

    lo, hi = min(y), max(y)
    pad = max((hi - lo) * 0.35, 8)
    fig.update_layout(
        height=height, margin=dict(l=0, r=0, t=8, b=0),
        paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)",
        font=dict(color=ft, size=11),
        xaxis=dict(showgrid=False, zeroline=False, linecolor=grid),
        yaxis=dict(showgrid=True, gridcolor=grid, zeroline=False,
                   range=[lo - pad, hi + pad]),
        hoverlabel=dict(bgcolor="#1a1a1a" if dark else "#ffffff",
                        font_color=tx, bordercolor=grid),
    )
    return fig


def gauge(value, dark):
    tx = "#f2f2f0" if dark else "#0b0b0b"
    track = "rgba(255,255,255,.1)" if dark else "rgba(0,0,0,.08)"
    fig = go.Figure(go.Indicator(
        mode="gauge+number", value=value,
        number=dict(font=dict(size=34, color=tx)),
        gauge=dict(
            axis=dict(range=[0, 200], tickwidth=0, tickcolor=track,
                      tickfont=dict(size=9)),
            bar=dict(color=tx, thickness=0.28),
            bgcolor="rgba(0,0,0,0)", borderwidth=0,
            steps=[dict(range=[0, 200], color=track)],
        )))
    fig.update_layout(height=170, margin=dict(l=14, r=14, t=6, b=6),
                      paper_bgcolor="rgba(0,0,0,0)", font=dict(color=tx))
    return fig


