@st.cache_data(show_spinner=False)
def read_snapshot():
    if not SNAPSHOT.exists():
        return None
    with open(SNAPSHOT) as f:
        snap = json.load(f)

    fc = pd.DataFrame(snap["forecast"])
    fc["timestamp"] = pd.to_datetime(fc["timestamp"], utc=True)
    hi = pd.DataFrame(snap["history"])
    hi["timestamp"] = pd.to_datetime(hi["timestamp"], utc=True)

    return {
        "mode": "snapshot", "current": snap["current"], "forecast": fc,
        "daily": pd.DataFrame(snap["daily"]), "history": hi,
        "models": snap["models"],
        "predicted_from": pd.Timestamp(snap["predicted_from"]),
        "source": "snapshot &middot; " + snap["generated_at"][:16].replace("T", " "),
        "pollutant_history": snap.get("pollutant_history", {}),
    }


@st.cache_data(ttl=900, show_spinner="Reading Hopsworks…")
def read_live():
    """Only called from the Refresh button - see the module docstring."""
    try:
        import importlib
        predict = importlib.import_module("09_predict")
        forecast, info = predict.forecast(verbose=False)
        daily = predict.daily_summary(forecast)
        df, _ = predict.load_features(verbose=False)
    except Exception as error:
        st.warning("Live read failed (%s). Showing the saved snapshot."
                   % type(error).__name__)
        return None

    latest = df.iloc[-1]
    day_ago = df["aqi"].iloc[-25] if len(df) > 25 else latest["aqi"]
    return {
        "mode": "live",
        "current": {
            "aqi": int(round(latest["aqi"])),
            "category": info["current_category"],
            "dominant_pollutant": info["dominant_pollutant"],
            "trend_24h": round(float(latest["aqi"] - day_ago), 1),
            "temperature": round(float(latest["temperature"]), 1),
            "humidity": int(round(latest["humidity"])),
            "wind_speed": round(float(latest["wind_speed"]), 1),
            "pollutants": {p: round(float(latest[p]), 1)
                           for p in ["pm2_5", "pm10", "no2", "o3", "co", "so2"]},
        },
        "forecast": forecast, "daily": daily,
        "history": df[["timestamp", "aqi"]].tail(24 * 30),
        "models": info["models"],
        "predicted_from": info["predicted_from"],
        "source": "live &middot; " + info["data_source"],
        "pollutant_history": {
            p: [round(float(x), 1) for x in df[p].tail(48).fillna(0)]
            for p in ["pm2_5", "pm10", "no2", "o3", "co", "so2"]},
    }


