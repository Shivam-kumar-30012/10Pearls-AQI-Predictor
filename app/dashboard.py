"""
10Pearls AQI Predictor - dashboard

Run locally:   streamlit run app/dashboard.py
Deployed on:   Streamlit Community Cloud

Layout
------
Four real tabs rather than a single long page with side-by-side
columns. The earlier version put the forecast chart beside a stack of
accuracy and pollutant cards; when the accuracy panel expanded, the
right column grew far taller than the left and left a large empty gap
under the chart. Tabs remove the problem entirely - each pane is full
width, so nothing has to line up against anything else.

Data sources, tried in order
----------------------------
  1. data/dashboard_snapshot.json  - committed to the repo, instant
  2. Hopsworks feature store       - on demand, via Refresh

Snapshot first is deliberate. Reading the store takes 15-25 seconds
when it works and times out after ~170 seconds when the free-tier
quota is spent, which would leave a visitor staring at a blank page.
The snapshot is regenerated by the daily training workflow, and the
forecast only changes daily anyway, so it is never meaningfully stale.
"""

