"""
10Pearls AQI Predictor - dashboard

Run locally:   streamlit run app/dashboard.py
Deployed on:   Streamlit Community Cloud

Navigation
----------
Views are chosen from the sidebar rather than tabs across the top.
Streamlit's st.tabs cannot be moved into the sidebar, so this uses a
radio styled to look like a nav list - same behaviour, and it keeps the
main area free for content.

Data source
-----------
data/dashboard_snapshot.json, committed to the repo and regenerated by
the daily training workflow immediately after the models are retrained.

There is deliberately no live-fetch path. An earlier version had one,
but it could not produce anything newer: the snapshot is rebuilt from
the same models in the same run, so a live read returns the same
forecast several seconds slower. Meanwhile Hopsworks' free tier hangs
for minutes at a time, and because Streamlit blocks on the call, that
froze the whole page. Reading a committed file cannot fail.
"""

