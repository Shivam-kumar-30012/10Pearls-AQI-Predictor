def line_chart(x, y, dark, height=300, markers=True, dividers=None):
    tx = "#f2f2f0" if dark else "#0b0b0b"
    grid = "rgba(255,255,255,.07)" if dark else "rgba(0,0,0,.09)"
    # Axis labels need real contrast, not the muted --ft grey. Plotly
    # also keeps its own default template colours unless every tickfont
    # is set explicitly, which is why the labels stayed light when the
    # page turned light.
    lab = "#8e8e88" if dark else "#4a4a46"

    lo, hi = min(y), max(y)
    pad = max((hi - lo) * 0.35, 8)
    floor = lo - pad

    fig = go.Figure()
    # Fill to the axis floor, not to zero. tozeroy reaches for y=0 while
    # the axis starts near 85, which drew a slab below the plot.
    fig.add_trace(go.Scatter(
        x=list(x) + list(x)[::-1], y=list(y) + [floor] * len(y),
        mode="lines", line=dict(width=0), fill="toself",
        fillcolor="rgba(141,198,63,.10)", hoverinfo="skip", showlegend=False))
    fig.add_trace(go.Scatter(
        x=x, y=y, mode="lines+markers" if markers else "lines",
        line=dict(color=tx, width=2, shape="spline", smoothing=0.6),
        marker=dict(size=5, color=tx),
        hovertemplate="AQI %{y}<br>%{x|%a %d %b %H:%M}<extra></extra>",
        showlegend=False))

    # No template override: template="none" strips Plotly's default axis
    # configuration along with its colours, which removed the tick labels
    # entirely. Setting every tickfont explicitly is enough to fix the
    # light-mode contrast on its own.
    fig.update_layout(
        height=height, margin=dict(l=0, r=0, t=10, b=0),
        paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)",
        font=dict(color=lab, size=11),
        xaxis=dict(showgrid=False, zeroline=False, linecolor=grid,
                   tickfont=dict(color=lab, size=11),
                   title_font=dict(color=lab)),
        yaxis=dict(showgrid=True, gridcolor=grid, zeroline=False,
                   range=[floor, hi + pad],
                   tickfont=dict(color=lab, size=11),
                   title_font=dict(color=lab)),
        hoverlabel=dict(bgcolor="#1a1a1a" if dark else "#ffffff",
                        font_color=tx, bordercolor=grid))

    for d in dividers or []:
        fig.add_vline(x=d, line_width=1, line_dash="dot", line_color=grid)
    return fig


def gauge(value, dark):
    tx = "#f2f2f0" if dark else "#0b0b0b"
    track = "rgba(255,255,255,.1)" if dark else "rgba(0,0,0,.08)"
    lab = "#8e8e88" if dark else "#4a4a46"
    fig = go.Figure(go.Indicator(
        mode="gauge+number", value=value,
        number=dict(font=dict(size=36, color=tx)),
        gauge=dict(axis=dict(range=[0, 200], tickwidth=0,
                             tickfont=dict(size=9, color=lab)),
                   bar=dict(color="#8DC63F", thickness=0.3),
                   bgcolor="rgba(0,0,0,0)", borderwidth=0,
                   steps=[dict(range=[0, 200], color=track)])))
    fig.update_layout(height=190, margin=dict(l=16, r=16, t=8, b=8),
                      paper_bgcolor="rgba(0,0,0,0)", font=dict(color=lab))
    return fig


def card(label, value, sub=""):
    return (f'<div class="card"><div class="lbl">{label}</div>'
            f'<div class="val">{value}</div><div class="sub">{sub}</div></div>')


def spark(series):
    """A 48-hour sparkline, or nothing if there is no history."""
    if not series or len(series) < 5:
        return ""
    lo, hi = min(series), max(series)
    rng = max(hi - lo, 1e-6)
    pts = " ".join("%.1f,%.1f" % (i / (len(series) - 1) * 70,
                                  14 - (v - lo) / rng * 12)
                   for i, v in enumerate(series))
    return (f'<svg viewBox="0 0 70 14" style="width:100%;height:14px;'
            f'margin-top:7px;opacity:.65"><polyline points="{pts}" fill="none" '
            f'stroke="var(--ac)" stroke-width="1.2"/></svg>')


