def main():
    if "dark" not in st.session_state:
        st.session_state.dark = True

    with st.sidebar:
        st.markdown('<div class="brand"><div class="brand-mark">1'
                    '<span class="brand-dot"></span>Pearls</div></div>'
                    '<div class="brand-sub">AQI predictor</div>',
                    unsafe_allow_html=True)
        st.markdown("<div style='height:18px'></div>", unsafe_allow_html=True)

        theme = st.radio("Theme", ["Dark", "Light"],
                         index=0 if st.session_state.dark else 1,
                         horizontal=True, label_visibility="collapsed")
        st.session_state.dark = theme == "Dark"

        st.markdown("<div style='height:8px'></div>", unsafe_allow_html=True)
        if st.button("Refresh forecast"):
            st.cache_data.clear()
            st.rerun()

    dark = st.session_state.dark
    inject_css(dark)

    data = get_data()
    if data is None:
        st.error("No data available. Run `python pipeline/10_build_snapshot.py` "
                 "to generate the dashboard snapshot.")
        return

    cur = data["current"]
    fc = data["forecast"]

    # ---- Header ----
    st.markdown(
        '<div class="brand"><div class="brand-mark">1'
        '<span class="brand-dot"></span>Pearls</div>'
        '<span style="width:1px;height:20px;background:var(--ln2)"></span>'
        '<span class="brand-sub">Air quality forecast &middot; Ghotki, Sindh</span>'
        '</div>', unsafe_allow_html=True)
    st.markdown("<div style='height:14px'></div>", unsafe_allow_html=True)

    # ---- Alert ----
    worst = fc.loc[fc["aqi"].idxmax()]
    if worst["aqi"] >= 150:
        st.markdown(
            f'<div class="alert"><b>Air quality alert</b> &nbsp;'
            f'AQI is forecast to reach {int(worst["aqi"])} '
            f'({worst["category"]}) at '
            f'{pd.Timestamp(worst["timestamp"]).strftime("%A %H:%M")}. '
            f'Sensitive groups should limit outdoor activity.</div>',
            unsafe_allow_html=True)

    # ---- Current conditions ----
    left, right = st.columns([1.15, 2])

    with left:
        arrow = "↓" if cur["trend_6h"] < 0 else "↑" if cur["trend_6h"] > 0 else "→"
        colour = CATEGORY_DOT.get(cur["category"], "#8e8e88")
        st.markdown(
            f'<div class="card" style="height:100%">'
            f'<div class="metric-label">RIGHT NOW</div>'
            f'<div style="display:flex;align-items:baseline;gap:12px;margin-top:8px">'
            f'<span class="hero-num">{cur["aqi"]}</span>'
            f'<span style="font-size:15px;color:var(--dm)">{arrow} '
            f'{abs(cur["trend_6h"]):.0f}</span></div>'
            f'<div style="margin-top:12px">'
            f'<span class="pill"><span class="dot" style="background:{colour}"></span>'
            f'{cur["category"]}</span></div>'
            f'<div class="metric-sub" style="margin-top:9px">'
            f'driven by {cur["dominant_pollutant"].replace("pm2_5","PM2.5").upper()}'
            f' &middot; vs 6 h ago</div></div>',
            unsafe_allow_html=True)

    with right:
        c1, c2, c3 = st.columns(3)
        for col, label, icon, val, sub in [
            (c1, "TEMPERATURE", "🌡", f'{cur["temperature"]:.0f}°',
             "Celsius"),
            (c2, "HUMIDITY", "💧", f'{cur["humidity"]}%',
             "Dry" if cur["humidity"] < 50 else "Humid"),
            (c3, "WIND", "🍃", f'{cur["wind_speed"]:.0f}',
             "km/h"),
        ]:
            with col:
                st.markdown(
                    f'<div class="card"><div class="metric-label">{label}</div>'
                    f'<div class="metric-value">{val}</div>'
                    f'<div class="metric-sub">{sub}</div></div>',
                    unsafe_allow_html=True)

        st.markdown("<div style='height:10px'></div>", unsafe_allow_html=True)
        d1, d2, d3 = st.columns(3)
        for col, (_, row) in zip([d1, d2, d3], data["daily"].iterrows()):
            colour = CATEGORY_DOT.get(row["category"], "#8e8e88")
            with col:
                st.markdown(
                    f'<div class="card"><div class="metric-label">DAY +{row["day"]}'
                    f'</div><div class="metric-value">{row["mean_aqi"]}</div>'
                    f'<div class="metric-sub">'
                    f'<span class="dot" style="background:{colour}"></span>'
                    f'{row["min_aqi"]}&ndash;{row["max_aqi"]}</div></div>',
                    unsafe_allow_html=True)

    st.markdown("<div style='height:22px'></div>", unsafe_allow_html=True)

    # ---- Forecast ----
    fl, fr = st.columns([2, 1])

    with fl:
        st.markdown("##### Forecast")
        mode = st.radio("View", ["Whole day", "Specific hour"],
                        horizontal=True, label_visibility="collapsed")

        if mode == "Whole day":
            day = st.radio("Day", ["Day +1", "Day +2", "Day +3"],
                           horizontal=True, label_visibility="collapsed")
            d = int(day[-1])
            block = fc[fc["day"] == d]
            st.plotly_chart(
                line_chart(block["timestamp"], block["aqi"], dark),
                use_container_width=True, config={"displayModeBar": False})
        else:
            h = st.slider("Hours ahead", 1, 72, 18, label_visibility="collapsed")
            row = fc[fc["hours_ahead"] == h].iloc[0]
            colour = CATEGORY_DOT.get(row["category"], "#8e8e88")
            when = pd.Timestamp(row["timestamp"])
            hc1, hc2 = st.columns([1, 1])
            with hc1:
                st.markdown(
                    f'<div class="card"><div class="metric-label">'
                    f'{when.strftime("%A %d %b &middot; %H:%M")}</div>'
                    f'<div class="hero-num" style="font-size:52px;margin-top:8px">'
                    f'{int(row["aqi"])}</div>'
                    f'<div style="margin-top:10px"><span class="pill">'
                    f'<span class="dot" style="background:{colour}"></span>'
                    f'{row["category"]}</span></div>'
                    f'<div class="metric-sub" style="margin-top:8px">'
                    f'{h} hours ahead &middot; day +{int(row["day"])} model</div></div>',
                    unsafe_allow_html=True)
            with hc2:
                st.plotly_chart(gauge(int(row["aqi"]), dark),
                                use_container_width=True,
                                config={"displayModeBar": False})

    with fr:
        st.markdown("##### Accuracy")
        with st.expander("Show model accuracy", expanded=False):
            for key in ["day1", "day2", "day3"]:
                m = data["models"].get(key, {})
                r2 = m.get("r2") or 0
                pct = int(round(r2 * 100))
                st.markdown(
                    f'<div style="display:flex;justify-content:space-between;'
                    f'font-size:12px"><span style="color:var(--dm)">'
                    f'Day +{key[-1]}</span><span>{pct}% &middot; '
                    f'R² {r2:.3f}</span></div>'
                    f'<div class="bar-track"><div class="bar-fill" '
                    f'style="width:{pct}%"></div></div>'
                    f'<div class="foot">MAE {m.get("mae") or 0:.1f} &middot; '
                    f'RMSE {m.get("rmse") or 0:.1f} &middot; '
                    f'{m.get("source","")}</div>'
                    f'<div style="height:12px"></div>',
                    unsafe_allow_html=True)
            st.markdown(
                '<div class="foot">Accuracy is R² on a held-out test period. '
                'It falls with lead time, as forecasts naturally do.</div>',
                unsafe_allow_html=True)

        st.markdown("<div style='height:10px'></div>", unsafe_allow_html=True)
        st.markdown("##### Pollutants")
        pol = cur["pollutants"]
        names = {"pm2_5": "PM2.5", "pm10": "PM10", "no2": "NO₂",
                 "o3": "O₃", "co": "CO", "so2": "SO₂"}
        rows = ""
        for k, label in names.items():
            unit = "ppm" if k == "co" else "µg/m³"
            val = pol[k] / 1145 if k == "co" else pol[k]
            rows += (f'<div style="display:flex;justify-content:space-between;'
                     f'padding:7px 0;border-bottom:1px solid var(--ln);'
                     f'font-size:12px"><span style="color:var(--dm)">{label}</span>'
                     f'<span>{val:.1f} <span style="color:var(--ft);font-size:10px">'
                     f'{unit}</span></span></div>')
        st.markdown(f'<div class="card">{rows}</div>', unsafe_allow_html=True)

    st.markdown("<div style='height:22px'></div>", unsafe_allow_html=True)

    # ---- History ----
    st.markdown("##### Recent history")
    span = st.radio("Range", ["24 hours", "7 days", "30 days"],
                    horizontal=True, label_visibility="collapsed")
    hours = {"24 hours": 24, "7 days": 24 * 7, "30 days": 24 * 30}[span]
    hist = data["history"].tail(hours)
    st.plotly_chart(line_chart(hist["timestamp"], hist["aqi"], dark, height=220),
                    use_container_width=True, config={"displayModeBar": False})

    st.markdown(
        f'<div class="foot" style="margin-top:18px">'
        f'Forecast issued {pd.Timestamp(data["predicted_from"]).strftime("%d %b %Y, %H:%M")} UTC '
        f'&middot; source: {data["source"]} '
        f'&middot; models retrained daily via GitHub Actions</div>',
        unsafe_allow_html=True)


if __name__ == "__main__":
    main()