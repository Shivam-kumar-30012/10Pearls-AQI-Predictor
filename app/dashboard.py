    if "dark" not in st.session_state:
        st.session_state.dark = True
    if "live" not in st.session_state:
        st.session_state.live = None

    with st.sidebar:
        st.markdown(
            '<div class="side-hero"><div class="side-in">'
            '<div class="side-mark">1<span class="side-dot"></span>Pearls</div>'
            '<div class="side-tag">AQI PREDICTOR</div>'
            '<div class="side-loc"><b>&#9679;</b> Ghotki, Sindh &middot; Pakistan'
            '</div></div></div>', unsafe_allow_html=True)

        st.markdown('<div class="side-head">DISPLAY</div>',
                    unsafe_allow_html=True)
        theme = st.radio("Theme", ["Dark", "Light"],
                         index=0 if st.session_state.dark else 1,
                         horizontal=True, label_visibility="collapsed")
        st.session_state.dark = theme == "Dark"

        st.markdown('<div class="side-head">DATA</div>', unsafe_allow_html=True)
        if st.button("Fetch live data"):
            st.cache_data.clear()
            st.session_state.live = read_live()
            st.rerun()

    dark = st.session_state.dark
    inject_css(dark)

    data = st.session_state.live or read_snapshot()
    if data is None:
        st.error("No data available. Run "
                 "`python pipeline/10_build_snapshot.py` first.")
        return

