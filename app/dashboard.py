def main():
    ss = st.session_state
    ss.setdefault("dark", True)
    ss.setdefault("live", None)
    # Marked seen as soon as it is shown, not when dismissed. Otherwise
    # switching theme before clicking through re-opens it every rerun.
    ss.setdefault("seen_welcome", False)
    ss.setdefault("fetching", False)

    with st.sidebar:
        st.markdown(LOGO_SVG
                    + '<div class="logo-sub">AQI PREDICTOR</div>'
                      '<div class="logo-loc"><b>&#9679;</b> Ghotki, Sindh '
                      '&middot; Pakistan</div>', unsafe_allow_html=True)

        view = st.radio("Section", VIEWS, label_visibility="collapsed")

        st.markdown('<div class="side-head">DISPLAY</div>',
                    unsafe_allow_html=True)
        st.markdown('<div class="theme-row">', unsafe_allow_html=True)
        theme = st.radio("Theme", ["Dark", "Light"],
                         index=0 if ss.dark else 1,
                         horizontal=True, label_visibility="collapsed")
        st.markdown('</div>', unsafe_allow_html=True)
        ss.dark = theme == "Dark"

        st.markdown('<div class="side-head">DATA</div>', unsafe_allow_html=True)
        show_help = st.button("How this works")
        fetch = st.button("Fetch live data")

    inject_css(ss.dark)

    # The fetch runs on the NEXT rerun, flagged in session state rather
    # than executed inline. Switching theme mid-fetch triggers a rerun
    # that would otherwise abandon the blocking call and leave the
    # overlay stranded; with a flag the overlay simply redraws, in the
    # new theme, and the fetch resumes.
    if fetch:
        ss.fetching = True
        st.rerun()

    if ss.fetching:
        overlay = st.empty()
        overlay.markdown(LOADER_HTML, unsafe_allow_html=True)
        ss.live = read_live()
        ss.fetching = False
        overlay.empty()
        st.rerun()

    data = ss.live or read_snapshot()
    if data is None:
        st.error("No data available. Run "
                 "`python pipeline/10_build_snapshot.py` first.")
        return

    st.markdown(
        '<div class="page-head"><h1>Air Quality Index</h1>'
        '<span class="page-sub">Ghotki, Sindh &middot; Pakistan</span></div>',
        unsafe_allow_html=True)

    {"Overview": view_overview, "Forecast": view_forecast,
     "Accuracy": view_accuracy, "History": view_history}[view](data, ss.dark)

    st.markdown(
        f'<div class="foot" style="margin-top:22px">Forecast issued '
        f'{pd.Timestamp(data["predicted_from"]).strftime("%d %b %Y, %H:%M")} UTC '
        f'&middot; {data["source"]} &middot; models retrained daily via '
        f'GitHub Actions</div>', unsafe_allow_html=True)

    # Dialog last, so the CSS above has already been applied to it
    if show_help or not ss.seen_welcome:
        ss.seen_welcome = True
        welcome()


if __name__ == "__main__":
    main()